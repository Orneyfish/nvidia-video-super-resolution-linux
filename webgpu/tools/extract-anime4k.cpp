// Turn an Anime4K mpv GLSL hook file (v3.2 / v4.0 CNN, MIT licence) into a small JS module of plain numbers that
// src/cnn.js turns into WGSL render passes. Dev-time tool; the generated modules are what is vendored in src/models/.
//
//   g++ -O2 -std=c++17 tools/extract-anime4k.cpp -o extract-anime4k
//   ./extract-anime4k <Anime4K_*.glsl> <out.js> <exported-name> [<note>]
//
// Source: https://github.com/bloc97/Anime4K (glsl/Upscale, glsl/Restore), Copyright (c) 2019-2021 bloc97, MIT.
// The GLSL files are NOT vendored (they are re-creatable from upstream); only the numbers and their structure are.
#include <array>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <iostream>
#include <map>
#include <regex>
#include <sstream>
#include <string>
#include <vector>
using namespace std;

struct Pass {
  string save, post = "null";
  vector<string> binds, w, bias{"0", "0", "0", "0"};
  map<int, pair<string, int>> defs;   // group -> (texture, sign)
  vector<array<string, 3>> taps;      // group, dx, dy
};

static string join(const vector<string>& v, const string& sep, const string& q = "") {
  string o; for (size_t i = 0; i < v.size(); i++) o += (i ? sep : "") + q + v[i] + q; return o;
}
static vector<string> split_commas(const string& s) {
  vector<string> v; stringstream ss(s); string t;
  while (getline(ss, t, ',')) { t.erase(0, t.find_first_not_of(" ")); t.erase(t.find_last_not_of(" ") + 1); v.push_back(t); }
  return v;
}
static string num(const string& s) { char b[32]; snprintf(b, sizeof b, "%g", atof(s.c_str())); return b; }   // "-1.0" -> "-1"

int main(int argc, char** argv) {
  if (argc < 4) { fprintf(stderr, "usage: extract-anime4k in.glsl out.js name [note]\n"); return 2; }
  string inFile = argv[1], outFile = argv[2], name = argv[3], note = argc > 4 ? argv[4] : "";
  ifstream in(inFile); stringstream buf; buf << in.rdbuf(); string text = buf.str();
  vector<string> blocks; size_t p = text.find("//!DESC ");
  while (p != string::npos) { size_t n = text.find("\n//!DESC ", p + 1); blocks.push_back(text.substr(p + 8, n == string::npos ? string::npos : n + 1 - (p + 8))); p = n == string::npos ? n : n + 1; }

  const regex re_def(R"(^#define go?_(\d+)(?:\([^)]*\))? (.*)$)"), re_tex(R"((\w+?)_tex(?:Off)?\()"),
      re_tap(R"((?:vec4 )?result (?:=|\+=) mat4\(([^)]*)\) \* (?:go_(\d+)\(([-\d.]+), ([-\d.]+)\)|g_(\d+));)"), re_bias(R"(result \+= vec4\(([^)]*)\);)");
  vector<Pass> passes; size_t nw = 0;
  for (auto& b : blocks) {
    Pass ps; string desc = b.substr(0, b.find('\n'));
    istringstream ls(b); string line;
    while (getline(ls, line)) {
      if (line.rfind("//!BIND ", 0) == 0) ps.binds.push_back(line.substr(8));
      else if (line.rfind("//!SAVE ", 0) == 0) ps.save = line.substr(8);
      smatch m;
      if (regex_match(line, m, re_def)) {
        string body = m[2], tex; smatch t; if (regex_search(body, t, re_tex)) tex = t[1];
        ps.defs[atoi(m[1].str().c_str())] = {tex, body.find("max(-(") != string::npos ? -1 : body.find("max((") != string::npos ? 1 : 0};
      }
    }
    if (desc.find("Depth-to-Space") != string::npos) { ps.post = "\"d2s\""; passes.push_back(ps); continue; }
    for (sregex_iterator it(b.begin(), b.end(), re_tap), e; it != e; ++it) {
      auto v = split_commas((*it)[1]); if (v.size() != 16) { fprintf(stderr, "mat4 with %zu values in %s\n", v.size(), desc.c_str()); return 1; }
      ps.w.insert(ps.w.end(), v.begin(), v.end());
      if ((*it)[2].matched) ps.taps.push_back({(*it)[2], num((*it)[3]), num((*it)[4])}); else ps.taps.push_back({(*it)[5], "0", "0"});
    }
    smatch bm; if (regex_search(b, bm, re_bias)) ps.bias = split_commas(bm[1]);
    if (b.find("return result + MAIN_tex(MAIN_pos);") != string::npos) ps.post = "\"addMain\"";
    if (ps.taps.empty()) { fprintf(stderr, "no taps parsed in %s\n", desc.c_str()); return 1; }
    nw += ps.w.size(); passes.push_back(ps);
  }

  string base = inFile.substr(inFile.rfind('/') == string::npos ? 0 : inFile.rfind('/') + 1);
  ofstream o(outFile);
  o << "// GENERATED by tools/extract-anime4k.cpp from " << base << " - do not edit.\n// " << note << "\n"
    << "// Weights and structure: Anime4K (https://github.com/bloc97/Anime4K), Copyright (c) 2019-2021 bloc97, MIT licence\n"
    << "// (full text in ../../LICENSE-Anime4K.txt). Each pass is a 3x3 (or 1x1) convolution over 4-channel feature maps:\n"
    << "//   out = bias + sum over taps [group, dx, dy] of  M_tap * g(tex_group(x+dx, y+dy)),   M_tap = column-major mat4 (16 numbers in w),\n"
    << "// where g is the identity, relu(x) or relu(-x) of the texture named in defs[group] = [texture, sign].\n"
    << "// post: 'addMain' adds the (bilinear) source, 'd2s' is the 2x depth-to-space + bilinear base of the upscale models.\n"
    << "export const " << name << " = {\n  name: \"" << name << "\",\n  passes: [\n";
  for (size_t i = 0; i < passes.size(); i++) {
    auto& ps = passes[i];
    o << "    { save: \"" << ps.save << "\", binds: [" << join(ps.binds, ",", "\"") << "], post: " << ps.post << ",";
    if (ps.post == "\"d2s\"") o << " }";
    else {
      o << "\n      defs: {"; bool f = true;
      for (auto& [g, d] : ps.defs) { o << (f ? "" : ",") << "\"" << g << "\":[\"" << d.first << "\"," << d.second << "]"; f = false; }
      o << "},\n      taps: [";
      for (size_t k = 0; k < ps.taps.size(); k++) o << (k ? "," : "") << "[" << ps.taps[k][0] << "," << ps.taps[k][1] << "," << ps.taps[k][2] << "]";
      o << "],\n      bias: [" << join(ps.bias, ", ") << "],\n      w: [" << join(ps.w, ", ") << "] }";
    }
    o << (i + 1 < passes.size() ? ",\n" : "\n");
  }
  o << "  ],\n};\nexport default " << name << ";\n";
  fprintf(stderr, "%s: %zu passes, %zu weights\n", outFile.c_str(), passes.size(), nw);
}
